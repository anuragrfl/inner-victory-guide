// Which series day it is in India today (0-based), or -1 when the series is over.
export function seriesIndex(ms = Date.now()) {
  const ist = new Date(ms + 5.5 * 3600 * 1000).toISOString().slice(0, 10);
  const d = Math.round((Date.parse(ist) - Date.parse(SERIES_START)) / 86400000);
  return d >= 0 && d < NIDHI_SERIES.length ? d : -1;
}
